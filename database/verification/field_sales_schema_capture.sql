BEGIN TRANSACTION READ ONLY;

WITH t AS (
  SELECT c.oid, c.relname::text AS rel, c.relrowsecurity AS rls
  FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
)
SELECT 1 AS ord, 'sequence' AS kind, c.relname::text AS name, 'CREATE SEQUENCE public.' || quote_ident(c.relname) || ';' AS ddl
FROM pg_class c
WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'S'
  AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')
UNION ALL
SELECT 2, 'table', rel, 'CREATE TABLE public.' || quote_ident(rel) || ' (' || (
  SELECT string_agg(quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
    || CASE WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
            WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
            WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
            ELSE coalesce(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), '') END
    || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END, ', ' ORDER BY a.attnum)
  FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped) || ');'
FROM t
UNION ALL
SELECT CASE con.contype WHEN 'p' THEN 3 WHEN 'u' THEN 4 WHEN 'c' THEN 5 ELSE 6 END, 'constraint', t.rel || '.' || con.conname,
  'ALTER TABLE public.' || quote_ident(t.rel) || ' ADD CONSTRAINT ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid) || ';'
FROM pg_constraint con JOIN t ON t.oid = con.conrelid
UNION ALL
SELECT 7, 'index', i.tablename || '.' || i.indexname, i.indexdef || ';'
FROM pg_indexes i
WHERE i.schemaname = 'public'
  AND NOT EXISTS (SELECT 1 FROM pg_constraint con JOIN pg_class ic ON ic.oid = con.conindid
                  WHERE ic.relname = i.indexname AND con.connamespace = 'public'::regnamespace)
UNION ALL
SELECT 8, 'function', n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname IN ('public', 'followup_audit_internal') AND p.prokind = 'f'
UNION ALL
SELECT 9, 'function_acl', n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
  'REVOKE ALL ON FUNCTION ' || n.nspname || '.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') FROM PUBLIC, anon, authenticated, service_role;'
  || coalesce(' GRANT EXECUTE ON FUNCTION ' || n.nspname || '.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') TO '
     || nullif(concat_ws(', ',
          CASE WHEN has_function_privilege('anon', p.oid, 'EXECUTE') THEN 'anon' END,
          CASE WHEN has_function_privilege('authenticated', p.oid, 'EXECUTE') THEN 'authenticated' END,
          CASE WHEN has_function_privilege('service_role', p.oid, 'EXECUTE') THEN 'service_role' END), '') || ';', '')
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname IN ('public', 'followup_audit_internal') AND p.prokind = 'f'
UNION ALL
SELECT 10, 'trigger', c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
FROM pg_trigger tg JOIN pg_class c ON c.oid = tg.tgrelid
WHERE c.relnamespace = 'public'::regnamespace AND NOT tg.tgisinternal
UNION ALL
SELECT 11, 'rls', rel, 'ALTER TABLE public.' || quote_ident(rel) || ' ENABLE ROW LEVEL SECURITY;' FROM t WHERE rls
UNION ALL
SELECT 12, 'policy', p.tablename || '.' || p.policyname,
  'CREATE POLICY ' || quote_ident(p.policyname) || ' ON public.' || quote_ident(p.tablename) || ' AS ' || p.permissive || ' FOR ' || p.cmd
  || ' TO ' || array_to_string(p.roles, ', ') || coalesce(' USING (' || p.qual || ')', '') || coalesce(' WITH CHECK (' || p.with_check || ')', '') || ';'
FROM pg_policies p WHERE p.schemaname = 'public'
UNION ALL
SELECT 13, 'grant', g.table_name || '.' || g.grantee,
  'GRANT ' || string_agg(g.privilege_type, ', ' ORDER BY g.privilege_type) || ' ON public.' || quote_ident(g.table_name) || ' TO ' || g.grantee || ';'
FROM information_schema.role_table_grants g JOIN t ON t.rel = g.table_name
WHERE g.table_schema = 'public' AND g.grantee IN ('anon', 'authenticated', 'service_role')
GROUP BY g.table_name, g.grantee
ORDER BY 1, 3;

ROLLBACK;
